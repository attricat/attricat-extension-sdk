#!/usr/bin/env node
// Generates the UI kit's Remote DOM elements and Preact components from the
// vendored contract. Run `pnpm generate` after replacing
// `contract/ui-kit-v1.schema.json`; the staleness test fails until you do.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
export const contractPath = join(packageRoot, 'contract', 'ui-kit-v1.schema.json');
export const generatedDir = join(packageRoot, 'src', 'generated');

const header = (what) =>
  `// Generated by scripts/generate.mjs from contract/ui-kit-v1.schema.json (UI kit ${what}).\n// Do not edit: change the contract and run \`pnpm generate\`.\n`;

const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name) => (identifier.test(name) ? name : JSON.stringify(name));
const capitalize = (name) => name[0].toUpperCase() + name.slice(1);
const indent = (text, by) => text.replaceAll('\n', `\n${' '.repeat(by)}`);

/** A TypeScript type for a JSON Schema fragment of the contract. */
export const schemaType = (schema) => {
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const parts = types.map((type) => {
    switch (type) {
      case 'string':
        return 'string';
      case 'integer':
      case 'number':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array': {
        const item = schema.items ? schemaType(schema.items) : 'unknown';
        return `readonly (${item})[]`;
      }
      case 'object':
        return objectType(schema);
      default:
        return 'unknown';
    }
  });
  return parts.join(' | ');
};

const objectType = (schema) => {
  const required = new Set(schema.required ?? []);
  const fields = Object.entries(schema.properties ?? {}).map(
    ([name, field]) => `readonly ${key(name)}${required.has(name) ? '' : '?'}: ${schemaType(field)};`,
  );
  if (schema.additionalProperties && typeof schema.additionalProperties === 'object')
    fields.push(`readonly [key: string]: ${schemaType(schema.additionalProperties)};`);
  if (!fields.length) return 'Record<string, never>';
  return `{\n  ${fields.join('\n  ')}\n}`;
};

/** The Remote DOM property type for a prop, so attribute values convert. */
const remoteType = (schema) => {
  const types = (Array.isArray(schema.type) ? schema.type : [schema.type]).filter(
    (type) => type !== 'null',
  );
  switch (types[0]) {
    case 'integer':
    case 'number':
      return 'Number';
    case 'boolean':
      return 'Boolean';
    case 'array':
      return 'Array';
    case 'object':
      return 'Object';
    default:
      return 'String';
  }
};

const doc = (lines) => {
  const body = lines.filter(Boolean);
  if (!body.length) return '';
  if (body.length === 1) return `/** ${body[0]} */\n`;
  return `/**\n${body.map((line) => ` * ${line}`).join('\n')}\n */\n`;
};

const propDoc = (prop) =>
  doc([
    prop.description?.en,
    prop.default !== undefined && prop.default !== null
      ? `@default ${JSON.stringify(prop.default)}`
      : '',
    prop.since && prop.since !== '1.0.0' ? `@since UI kit ${prop.since}` : '',
  ]);

const eventProp = (event) => `on${capitalize(event)}`;

const childrenType = {
  none: 'never',
  text: 'TextChildren',
  elements: 'ComponentChildren',
};

/** Renders every generated file of the contract, keyed by path in `src/generated`. */
export const generate = (contract) => {
  const elements = Object.entries(contract.elements);
  const out = {};

  // version.ts: side-effect free, so tools can read it without a DOM.
  out['version.ts'] = `${header(contract.version)}
/** The UI kit contract version these components implement. */
export const UI_KIT_VERSION = ${JSON.stringify(contract.version)};
/** Every UI kit version the contract describes. */
export const UI_KIT_VERSIONS = ${JSON.stringify(contract.versions)} as const;
/** Icons the host draws; elements name one. */
export const UI_KIT_ICONS = ${JSON.stringify(contract.icons)} as const;
export type UiKitIcon = (typeof UI_KIT_ICONS)[number];
/** Host bounds on lengths and counts, in characters or items. */
export const UI_KIT_LIMITS = ${JSON.stringify(contract.limits, null, 2)} as const;
/** The custom-element tag of every UI kit element. */
export const UI_KIT_TAGS = {
${elements.map(([name, element]) => `  ${name}: ${JSON.stringify(element.tag)},`).join('\n')}
} as const;
export type UiKitElementName = keyof typeof UI_KIT_TAGS;

/** What the host accepts for each element: props, events, children and slots. */
export const UI_KIT_ELEMENTS = {
${elements
  .map(
    ([name, element]) => `  ${name}: {
    tag: ${JSON.stringify(element.tag)},
    since: ${JSON.stringify(element.since)},
    props: ${JSON.stringify(
      Object.fromEntries(
        Object.entries(element.props).map(([prop, item]) => [
          prop,
          { required: Boolean(item.required), since: item.since },
        ]),
      ),
    )},
    events: ${JSON.stringify(Object.keys(element.events))},
    children: ${JSON.stringify(element.children.kind)},
    slots: ${JSON.stringify(
      Object.fromEntries(Object.entries(element.slots).map(([slot, item]) => [slot, item.allowed])),
    )},
    methods: ${JSON.stringify(element.methods)},
    accessibility: ${JSON.stringify(element.accessibility)},
  },`,
  )
  .join('\n')}
} as const;
`;

  // elements.ts: Remote DOM custom elements, defined under the contract's tags.
  const elementBlocks = elements.map(([name, element]) => {
    const props = Object.entries(element.props);
    const events = Object.entries(element.events);
    const required = (prop) => Boolean(prop.required);
    const properties = props.length
      ? `{\n${props
          .map(
            ([prop, item]) =>
              `  ${indent(propDoc(item), 2)}${key(prop)}${required(item) ? '' : '?'}: ${indent(
                schemaType(item.schema),
                2,
              )};`,
          )
          .join('\n')}\n}`
      : '{}';
    const payloads = events
      .map(
        ([event, item]) =>
          `${doc([item.description?.en])}export type ${name}${capitalize(event)}Payload = ${objectType({
            properties: item.payload,
            required: Object.keys(item.payload),
          })};\n`,
      )
      .join('');
    const listeners = events.length
      ? `{\n${events
          .map(
            ([event]) =>
              `  ${key(event)}(event: RemoteEvent<${name}${capitalize(event)}Payload>): void;`,
          )
          .join('\n')}\n}`
      : '{}';
    const methods = element.methods.length
      ? `{\n${element.methods.map((method) => `  ${key(method)}(): void;`).join('\n')}\n}`
      : '{}';
    const slots = Object.keys(element.slots).length
      ? `{\n${Object.keys(element.slots)
          .map((slot) => `  ${key(slot)}?: true;`)
          .join('\n')}\n}`
      : '{}';
    const options = [
      props.length
        ? `  properties: {\n${props
            .map(([prop, item]) => `    ${key(prop)}: { type: ${remoteType(item.schema)} },`)
            .join('\n')}\n  },`
        : '',
      events.length ? `  events: ${JSON.stringify(events.map(([event]) => event))},` : '',
      element.methods.length ? `  methods: ${JSON.stringify(element.methods)},` : '',
      Object.keys(element.slots).length
        ? `  slots: ${JSON.stringify(Object.keys(element.slots))},`
        : '',
    ].filter(Boolean);
    return `${doc([`Props of \`${name}\`: ${element.description?.en ?? ''}`])}export interface ${name}Properties ${properties}
${payloads}export interface ${name}EventListeners ${listeners}
export interface ${name}Methods ${methods}
export interface ${name}Slots ${slots}
${doc([`The \`<${element.tag}>\` remote element.`])}export const ${name}Element = createRemoteElement<
  ${name}Properties,
  ${name}Methods,
  ${name}Slots,
  ${name}EventListeners
>({${options.length ? `\n${options.join('\n')}\n` : ''}});
export type ${name}Instance = InstanceType<typeof ${name}Element>;
`;
  });

  out['elements.ts'] = `${header(contract.version)}
// The DOM polyfill must exist before any element class is created.
import '@remote-dom/core/polyfill';
import { createRemoteElement, type RemoteEvent } from '@remote-dom/core/elements';

${elementBlocks.join('\n')}
/** Every UI kit element class by its custom-element tag. */
export const UI_KIT_ELEMENT_CLASSES = {
${elements.map(([name, element]) => `  ${JSON.stringify(element.tag)}: ${name}Element,`).join('\n')}
} as const;

/** Defines every UI kit element; elements already defined are left alone. */
export const defineUiKitElements = () => {
  for (const [tag, element] of Object.entries(UI_KIT_ELEMENT_CLASSES))
    if (!customElements.get(tag)) customElements.define(tag, element);
};

defineUiKitElements();

declare global {
  interface HTMLElementTagNameMap {
${elements.map(([name, element]) => `    ${JSON.stringify(element.tag)}: ${name}Instance;`).join('\n')}
  }
}
`;

  // components.ts: Preact components over the elements.
  const componentBlocks = elements.map(([name, element]) => {
    const events = Object.entries(element.events);
    const slots = Object.entries(element.slots);
    const members = [
      ...events.map(
        ([event, item]) =>
          `  ${indent(doc([item.description?.en, `Receives the host's \`${event}\` payload.`]), 2)}${eventProp(
            event,
          )}?: (payload: ${name}${capitalize(event)}Payload) => unknown;`,
      ),
      ...slots.map(
        ([slot, item]) =>
          `  ${indent(
            doc([
              item.description?.en,
              `Accepts ${item.allowed.map((allowed) => `\`<${allowed}>\``).join(' or ')}; equivalent to a child with \`slot="${slot}"\`.`,
            ]),
            2,
          )}${key(slot)}?: VNode;`,
      ),
      `  /** ${element.children.kind === 'none' ? 'Takes no children.' : element.children.kind === 'text' ? 'Plain text only.' : 'UI kit elements.'} */\n  children?: ${childrenType[element.children.kind]};`,
      `  /** The parent's slot this element fills, such as \`"action"\`. */\n  slot?: string;`,
      `  key?: Key;`,
      `  ref?: Ref<${name}Instance>;`,
    ];
    return `${doc([element.description?.en, `Draws \`<${element.tag}>\`.`])}export interface ${name}Props extends ${name}Properties {
${members.join('\n')}
}
export const ${name}: FunctionComponent<${name}Props> = uiKitComponent(${JSON.stringify(name)}, ${JSON.stringify(element.tag)}, ${name}Element, ${JSON.stringify(
      Object.fromEntries(events.map(([event]) => [eventProp(event), event])),
    )});
`;
  });

  out['components.ts'] = `${header(contract.version)}
import type { ComponentChildren, FunctionComponent, Key, Ref, VNode } from 'preact';
import { uiKitComponent, type TextChildren } from '../component.js';
import {
${elements
  .flatMap(([name, element]) => [
    `${name}Element`,
    `type ${name}Instance`,
    `type ${name}Properties`,
    ...Object.keys(element.events).map((event) => `type ${name}${capitalize(event)}Payload`),
  ])
  .map((item) => `  ${item},`)
  .join('\n')}
} from './elements.js';

${componentBlocks.join('\n')}`;

  return out;
};

const main = () => {
  const contract = JSON.parse(readFileSync(contractPath, 'utf8'));
  mkdirSync(generatedDir, { recursive: true });
  for (const [file, content] of Object.entries(generate(contract)))
    writeFileSync(join(generatedDir, file), content);
  console.log(`Generated UI kit ${contract.version} into src/generated`);
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
